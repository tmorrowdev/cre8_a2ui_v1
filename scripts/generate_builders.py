"""Generate typed a2ui-agent-sdk builder classes for the cre8 v1.0 catalog.

The SDK ships builders for the basic catalog only (generated by a2ui_cli, which
is not published). Macros return builder trees, so cre8 needs its own. This
script reads `catalog/cre8_wc.v1.json` and writes `builders/cre8.py`.

Run after regenerating the catalog:  uv run python scripts/generate_builders.py
"""

from __future__ import annotations

import json
import keyword
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "src/a2ui_apps/catalog/cre8_wc.v1.json"
OUT = ROOT / "src/a2ui_apps/builders/cre8.py"

PRIMITIVE = {"string": "str", "number": "float", "integer": "int", "boolean": "bool", "array": "list[Any]", "object": "dict[str, Any]"}


def literal_type(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in schema and schema["$ref"].startswith("#/$defs/"):
        return literal_type(defs[schema["$ref"].rsplit("/", 1)[-1]], defs)
    if "enum" in schema:
        return "Literal[" + ", ".join(json.dumps(v) for v in schema["enum"]) + "]"
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(PRIMITIVE.get(x, "Any") for x in t)
    if t in PRIMITIVE:
        return PRIMITIVE[t]
    if "oneOf" in schema or "anyOf" in schema:
        return "Any"
    return "Any"


def field_type(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    ref = schema.get("$ref", "")
    if ref.endswith("/ChildList"):
        return "ChildList"
    if ref.endswith("/Action"):
        return "Action"
    if "anyOf" in schema:
        branches = schema["anyOf"]
        literal = next((b for b in branches if not b.get("$ref", "").endswith(("DataBinding", "FunctionCall"))), {})
        bindable = any(b.get("$ref", "").endswith("DataBinding") for b in branches)
        return literal_type(literal, defs) + (" | DataBinding" if bindable else "")
    return literal_type(schema, defs)


def properties_of(schema: dict[str, Any], defs: dict[str, Any]) -> dict[str, Any]:
    props: dict[str, Any] = {}
    for part in schema.get("allOf", [schema]):
        ref = part.get("$ref", "")
        source = defs[ref.rsplit("/", 1)[-1]] if ref.startswith("#/$defs/") else part
        props.update(source.get("properties", {}))
    props.pop("component", None)
    return props


def main() -> None:
    doc = json.loads(CATALOG.read_text())
    defs = doc["$defs"]
    lines = [
        '"""Type-safe a2ui-agent-sdk builders for the cre8-wc v1.0 catalog.',
        "",
        "AUTO-GENERATED by scripts/generate_builders.py from catalog/cre8_wc.v1.json - do not edit.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Literal, Optional",
        "",
        "from pydantic import Field",
        "",
        "from a2ui.builder.v1_0 import Action, ChildList, ComponentBuilderNode, DataBinding",
        "",
        f'CATALOG_ID = "{doc["catalogId"]}"',
        "",
        "",
        "class Cre8Node(ComponentBuilderNode, catalog_id=CATALOG_ID):",
        '    """Base for every cre8 catalog builder; stamps the cre8 catalog id."""',
        "",
    ]
    names = []
    for name, schema in doc["components"].items():
        names.append(name)
        required = set()
        for part in schema.get("allOf", [schema]):
            required |= set(part.get("required", []))
        doc_line = (schema.get("description") or name).replace('"""', "'''").replace("\\", "\\\\")
        lines += ["", f"class {name}(Cre8Node):", f'    r"""{doc_line}"""', "", f'    component: Literal["{name}"] = "{name}"']
        for prop, prop_schema in properties_of(schema, defs).items():
            attr = prop + "_" if keyword.iskeyword(prop) else prop
            typ = field_type(prop_schema, defs)
            if prop in required:
                default = f' = Field(alias="{prop}")' if attr != prop else ""
                lines.append(f"    {attr}: {typ}{default}")
            elif attr != prop:
                lines.append(f'    {attr}: Optional[{typ}] = Field(default=None, alias="{prop}")')
            else:
                lines.append(f"    {attr}: Optional[{typ}] = None")
        lines.append("")
    lines += ["", "__all__ = [" + ", ".join(f'"{n}"' for n in ["CATALOG_ID", "Cre8Node", *names]) + "]", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(names)} builders)")


if __name__ == "__main__":
    main()
